export type MoodId =
  | 'Late Nights'
  | 'Late Night'
  | 'Romance'
  | 'Romantic'
  | 'Party'
  | 'Sad'
  | 'Chill'
  | 'Focus'
  | 'Feel Good'
  | 'Happy'
  | 'Road Trip'
  | 'Travel'
  | 'Workout'
  | 'Rainy Day'
  | 'Motivation'
  | 'Nostalgic Classics';

export function normalizeMoodId(mood: string): MoodId {
  const m = mood.toLowerCase().trim();
  if (m === 'romantic' || m === 'romance') return 'Romance';
  if (m === 'happy' || m === 'feel good' || m === 'feelgood') return 'Feel Good';
  if (m === 'travel' || m === 'road trip' || m === 'roadtrip') return 'Road Trip';
  if (m === 'late night' || m === 'late nights' || m === 'latenight' || m === 'latenights') return 'Late Nights';
  if (m === 'workout' || m === 'gym') return 'Workout';
  if (m === 'rainy day' || m === 'rainyday' || m === 'rain') return 'Rainy Day';
  if (m === 'motivation' || m === 'motivational') return 'Motivation';
  if (m === 'nostalgic classics' || m === 'nostalgic' || m === 'classics' || m === 'nostalgia') return 'Nostalgic Classics';
  if (m === 'party') return 'Party';
  if (m === 'sad') return 'Sad';
  if (m === 'chill') return 'Chill';
  if (m === 'focus') return 'Focus';
  return (mood as MoodId) || 'Late Nights';
}

